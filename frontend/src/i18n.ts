// Lightweight, dependency-free i18n. Reactive `locale` + `t(key, params)`.
// Default Polish (the product is used by a Polish team auditing Polish domains);
// English is kept and switchable. Dynamic content (personas, findings, narrative)
// comes from the LLM already localized, so only UI chrome lives here.
import { ref } from 'vue'

export type Locale = 'pl' | 'en'

const STORAGE_KEY = 'ux_locale'
function initial(): Locale {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    if (v === 'pl' || v === 'en') return v
  } catch { /* ignore */ }
  return 'pl'
}

export const locale = ref<Locale>(initial())

export function setLocale(l: Locale) {
  locale.value = l
  try { localStorage.setItem(STORAGE_KEY, l) } catch { /* ignore */ }
}

